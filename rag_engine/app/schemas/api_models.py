from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field

class IngestTextRequest(BaseModel):
    text: str = Field(..., description="Raw text or markdown document content to index")
    source: str = Field(default="manual_entry", description="Source file name or identifier")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Custom metadata key-values")

class IngestResponse(BaseModel):
    status: str = Field(..., description="'success' or 'error'")
    chunks_indexed: int = Field(..., description="Number of chunks created and indexed")
    source: str = Field(..., description="Source identifier")
    collection: str = Field(..., description="Target Qdrant collection")
    chunk_ids: Optional[List[str]] = Field(default=None, description="List of generated chunk IDs")
    message: Optional[str] = None

class SourceChunk(BaseModel):
    content: str = Field(..., description="Text content of the chunk")
    source: str = Field(..., description="Source document name")
    chunk_id: str = Field(..., description="Unique chunk identifier")
    score: Optional[float] = Field(default=None, description="FlashRank rerank score")
    dense_score: Optional[float] = Field(default=None, description="Qdrant dense similarity score")
    sparse_score: Optional[float] = Field(default=None, description="BM25 sparse score")

class QueryRequest(BaseModel):
    query: str = Field(..., min_length=2, description="User question or search query")
    stream: Optional[bool] = Field(default=False, description="Enable streaming response")

class QueryResponse(BaseModel):
    answer: str = Field(..., description="Final grounded answer generated by the LLM")
    sources: List[SourceChunk] = Field(default_factory=list, description="Top-k relevant cited chunks")
    rewritten_query: Optional[str] = Field(default=None, description="Rewritten query if transformation was triggered")
    relevance_score: str = Field(..., description="'yes' or 'no' grading of retrieved context")
    rewrite_count: int = Field(default=0, description="Number of query reformulations executed")
    latency_ms: float = Field(..., description="Total execution time in milliseconds")
    route_history: List[str] = Field(default_factory=list, description="Sequence of LangGraph nodes executed")
    warning: Optional[str] = Field(default=None, description="Warning if context was insufficient after max rewrites")

class HealthResponse(BaseModel):
    status: str = Field(..., description="'healthy' or 'degraded'")
    version: str = Field(default="1.0.0")
    qdrant_status: str = Field(..., description="Vector store connectivity status")
    total_documents_indexed: int = Field(default=0, description="Total chunks in vector index")
    bm25_initialized: bool = Field(..., description="Whether BM25 retriever has documents loaded")
    gemini_configured: bool = Field(..., description="Whether Google Gemini API key is configured")
